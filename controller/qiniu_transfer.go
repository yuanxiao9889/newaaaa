func sealQiniuClaim(c *gin.Context, claim service.TransferDownloadClaim) (string, error) {
	owner, err := model.GetUserById(c.GetInt("id"), false)
	if err != nil || owner.Status != common.UserStatusEnabled {
		return "", service.ErrReferenceUnavailable
	}
	digest := sha256.Sum256([]byte(c.GetString("token_key")))
	claim.Version = 1
	claim.UserID = owner.Id
	claim.AuthVersion = owner.AuthVersion
	claim.TokenID = c.GetInt("token_id")
	claim.TokenDigest = hex.EncodeToString(digest[:])
	claim.IssuedAt = time.Now().Unix()
	claim.ExpiresAt = claim.IssuedAt + 300
	return service.SealTransferDownload(claim)
}

func PrepareQiniuReferenceChunk(c *gin.Context) {
	c.Header("Cache-Control", "no-store")
	if !service.QiniuDirectUploadEnabled() {
		referenceUploadError(c, service.ErrReferenceUnavailable)
		return
	}
	var input struct {
		UploadID string `json:"upload_id"`
		Index    int    `json:"index"`
		SHA256   string `json:"sha256"`
	}
	c.Request.Body = http.MaxBytesReader(c.Writer, c.Request.Body, 4096)
	if common.DecodeJson(c.Request.Body, &input) != nil {
		referenceUploadError(c, service.ErrReferenceInvalid)
		return
	}
	claim, _, err := service.ReferenceUploads.QiniuChunk(c.GetInt("id"), input.UploadID, input.Index, input.SHA256)
	if err != nil {
		referenceUploadError(c, err)
		return
	}
	claim.ResourceID = claim.ObjectKey
	ticket, err := sealQiniuClaim(c, claim)
	if err != nil {
		referenceUploadError(c, err)
		return
	}
	// Recheck the live account/token before releasing a native storage grant.
	// Completion and task submission still require current business authorization.
	claim, err = service.OpenAuthorizedTransferDownload(ticket, time.Now())
	if err != nil {
		c.AbortWithStatus(403)
		return
	}
	grant, ready, err := service.ReferenceUploads.AuthorizeQiniuUpload(c.Request.Context(), claim)
	if err != nil {
		referenceUploadError(c, err)
		return
	}
	if ready {
		result, err := service.ReferenceUploads.ImportQiniuChunk(c.Request.Context(), claim)
		if err != nil {
			referenceUploadError(c, err)
			return
		}
		c.JSON(200, gin.H{"status": "received", "receipt": result})
		return
	}
	c.JSON(200, gin.H{"status": "upload_required", "upload_method": "POST", "upload_url": grant.URL,
		"upload_token": grant.Token, "object_key": grant.Key, "size": grant.Size, "sha256": grant.SHA256,
		"upload_expires_at": grant.ExpiresAt, "ticket": ticket, "expires_at": claim.ExpiresAt})
}

func CompleteQiniuReferenceChunk(c *gin.Context) {
	c.Header("Cache-Control", "no-store")
	var input struct {
		Ticket string `json:"ticket"`
	}
	c.Request.Body = http.MaxBytesReader(c.Writer, c.Request.Body, 20<<10)
	if common.DecodeJson(c.Request.Body, &input) != nil {
		referenceUploadError(c, service.ErrReferenceInvalid)
		return
	}
	claim, err := service.OpenAuthorizedTransferDownload(input.Ticket, time.Now())
	if err != nil || claim.Route != "qiniu-upload" || claim.UserID != c.GetInt("id") || service.ReferenceUploads == nil {
		c.AbortWithStatus(403)
		return
	}
	result, err := service.ReferenceUploads.ImportQiniuChunk(c.Request.Context(), claim)
	writeResumableReference(c, result, err)
}

// The edge/CDN supplies a static server-side callback secret, never the desktop.
// Original path/host fields must be generated by CDN, and decisions never cached.
func AuthorizeQiniuTransfer(c *gin.Context) {
	c.Header("Cache-Control", "no-store")
	secret := os.Getenv("TRANSFER_QINIU_CALLBACK_SECRET")
	if len(secret) < 32 || len(c.Request.Header.Values("X-Opics-Callback-Key")) != 1 || subtle.ConstantTimeCompare([]byte(secret), []byte(c.GetHeader("X-Opics-Callback-Key"))) != 1 || len(c.Request.Header.Values("X-Opics-Qiniu-Ticket")) != 1 || c.Request.ContentLength != 0 || len(c.Request.TransferEncoding) > 0 {
		c.AbortWithStatus(401)
		return
	}
	claim, err := service.OpenAuthorizedTransferDownload(c.GetHeader("X-Opics-Qiniu-Ticket"), time.Now())
	if err != nil {
		c.AbortWithStatus(403)
		return
	}
	if claim.Route == "qiniu-upload" && c.Query("operation") == "upload" && service.QiniuTransferOrigin(true) != "" {
		grant, ready, err := service.ReferenceUploads.AuthorizeQiniuUpload(c.Request.Context(), claim)
		if err != nil {
			referenceUploadError(c, err)
			return
		}
		if ready {
			c.JSON(200, gin.H{"ready": true})
			return
		}
		c.JSON(200, grant)
		return
	}
	if claim.Route == "qiniu-download" && c.Query("operation") == "origin-read" && service.QiniuTransferOrigin(false) != "" && c.Query("path") == "/"+claim.ObjectKey {
		c.JSON(200, gin.H{"url": service.ReferenceUploads.QiniuOriginReadURL(claim.ObjectKey)})
		return
	}
	if claim.Route != "qiniu-download" || service.QiniuTransferOrigin(false) == "" || c.Query("operation") != "download" {
		c.AbortWithStatus(403)
		return
	}
	origin, _ := url.Parse(service.QiniuTransferOrigin(false))
	if c.Query("host") != origin.Host || c.Query("path") != "/"+claim.ObjectKey || (c.Query("method") != "GET" && c.Query("method") != "HEAD") {
		c.AbortWithStatus(403)
		return
	}
	c.Status(204)
}

func createQiniuDownload(c *gin.Context, source *transferDownloadSource) {
	origin := service.QiniuTransferOrigin(false)
	if origin == "" {
		referenceUploadError(c, service.ErrReferenceUnavailable)
		return
	}
	ctx, cancel := context.WithTimeout(c.Request.Context(), 2*time.Minute)
	defer cancel()
	identity := strconv.Itoa(c.GetInt("id")) + ":" + source.resource + ":" + source.version
	// Relay content access tokens rotate; they must not change object identity.
	if source.version == "" && source.route != "relay" {
		identity += ":" + source.bridge
	}
	key, err := service.ReferenceUploads.PutQiniuResult(ctx, identity, source.bridge, source.version, source.headers, source.redirectHosts)
	if err != nil {
		referenceUploadError(c, err)
		return
	}
	resource := sha256.Sum256([]byte(strconv.Itoa(c.GetInt("id")) + ":" + source.resource))
	claim := service.TransferDownloadClaim{Route: "qiniu-download", ObjectKey: key, ResourceID: hex.EncodeToString(resource[:]), ResourceVersion: source.version}
	ticket, err := sealQiniuClaim(c, claim)
	if err != nil {
		referenceUploadError(c, err)
		return
	}
	c.JSON(200, gin.H{"protocol_version": 1, "url": origin + "/" + key, "ticket": ticket,
		"resource_id": claim.ResourceID, "resource_version": source.version, "expires_at": time.Now().Unix() + 300})
}
